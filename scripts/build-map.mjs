/**
 * Bakes the dotted world basemap and the projected route endpoints.
 *
 * dotted-map ships a land-polygon dataset far too heavy to send to the
 * browser, and neither the grid nor the port coordinates ever change — so
 * both are generated here, at build time, into static assets.
 *
 * Run with: npm run build:map
 */
import DottedMap from "dotted-map";
import { mkdirSync, writeFileSync } from "node:fs";

const HEIGHT = 62;

const map = new DottedMap({ height: HEIGHT, grid: "diagonal" });

/* --------------------------------------------------------------- basemap */

const svg = map.getSVG({
  radius: 0.22,
  color: "#5fb37d55",
  shape: "circle",
  backgroundColor: "transparent",
});

mkdirSync("public/map", { recursive: true });
writeFileSync("public/map/world-dots.svg", svg);

/* ----------------------------------------------------- projected points */

// Keep in step with `markets` in src/data/content.ts.
const ORIGIN = { id: "bissau", city: "Bissau", country: "Guinea-Bissau", lat: 11.86, lng: -15.6 };

const DESTINATIONS = [
  { id: "india", city: "Mumbai / Tuticorin", country: "India", lat: 19.08, lng: 72.88 },
  { id: "vietnam", city: "Ho Chi Minh City", country: "Vietnam", lat: 10.82, lng: 106.63 },
  { id: "uae", city: "Jebel Ali", country: "UAE", lat: 25.01, lng: 55.06 },
  { id: "singapore", city: "Singapore", country: "Singapore", lat: 1.29, lng: 103.85 },
  { id: "netherlands", city: "Rotterdam", country: "Netherlands", lat: 51.92, lng: 4.48 },
  { id: "turkiye", city: "Istanbul", country: "Türkiye", lat: 41.01, lng: 28.98 },
];

// addPin returns the point already projected into the SVG's coordinate space,
// which is the only reliable way to line markers up with the dot grid.
const project = (p) => {
  const { x, y } = map.addPin({ lat: p.lat, lng: p.lng });
  return { ...p, x: Number(x.toFixed(3)), y: Number(y.toFixed(3)) };
};

const origin = project(ORIGIN);
const destinations = DESTINATIONS.map(project);

/* -------------------------------------------------- Guinea-Bissau inset */

// Country-filtered and cropped to its own bounding box, so the silhouette
// of Guinea-Bissau — including the Bijagós archipelago — reads clearly.
const GW_BOUNDS = {
  lat: { min: 10.6, max: 12.9 },
  lng: { min: -16.9, max: -13.5 },
};

const gw = new DottedMap({
  height: 54,
  grid: "diagonal",
  countries: ["GNB"],
  region: GW_BOUNDS,
});

const gwSvg = gw.getSVG({
  radius: 0.32,
  color: "#5fb37daa",
  shape: "circle",
  backgroundColor: "transparent",
});

writeFileSync("public/map/guinea-bissau-dots.svg", gwSvg);

/** The producing regions we buy in, plus the capital and export port. */
const GW_PLACES = [
  { id: "bissau", name: "Bissau", role: "Capital · export port", lat: 11.8637, lng: -15.5977, primary: true },
  { id: "bafata", name: "Bafatá", role: "Producing region", lat: 12.1662, lng: -14.6614 },
  { id: "gabu", name: "Gabú", role: "Producing region", lat: 12.28, lng: -14.22 },
  { id: "oio", name: "Oio", role: "Producing region", lat: 12.4833, lng: -15.2167 },
  { id: "quinara", name: "Quinara", role: "Producing region", lat: 11.7667, lng: -15.1833 },
  { id: "cacheu", name: "Cacheu", role: "Producing region", lat: 12.2739, lng: -16.165 },
];

const gwPlaces = GW_PLACES.map((p) => {
  const { x, y } = gw.addPin({ lat: p.lat, lng: p.lng });
  return { ...p, x: Number(x.toFixed(3)), y: Number(y.toFixed(3)) };
});

const ts = `// AUTO-GENERATED by scripts/build-map.mjs — do not edit by hand.
// Coordinates are projected into the viewBox of /map/world-dots.svg.

export type MapPoint = {
  id: string;
  city: string;
  country: string;
  lat: number;
  lng: number;
  x: number;
  y: number;
};

/** The viewBox of the generated basemap. */
export const MAP_VIEWBOX = { w: ${map.width}, h: ${map.height} } as const;

export const mapOrigin: MapPoint = ${JSON.stringify(origin, null, 2)};

export const mapDestinations: MapPoint[] = ${JSON.stringify(destinations, null, 2)};

/* ------------------------------------------------------- Guinea-Bissau */

export type GwPlace = {
  id: string;
  name: string;
  role: string;
  lat: number;
  lng: number;
  x: number;
  y: number;
  primary?: boolean;
};

/** The viewBox of /map/guinea-bissau-dots.svg. */
export const GW_VIEWBOX = { w: ${gw.width}, h: ${gw.height} } as const;

export const gwPlaces: GwPlace[] = ${JSON.stringify(gwPlaces, null, 2)};
`;

writeFileSync("src/data/map-points.ts", ts);

console.log(
  `world-dots.svg ${Math.round(svg.length / 1024)}kb (${map.width}x${map.height}) · ` +
    `guinea-bissau-dots.svg ${Math.round(gwSvg.length / 1024)}kb (${gw.width}x${gw.height}) · ` +
    `${destinations.length} destinations · ${gwPlaces.length} places`,
);
