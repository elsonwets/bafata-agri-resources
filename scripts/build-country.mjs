/**
 * Turns the vendored Guinea-Bissau ADM1 GeoJSON into ready-to-render SVG
 * paths, one per administrative region.
 *
 * Projection is equirectangular with a cos(latitude) correction — for a
 * country 250 km across that is indistinguishable from anything fancier,
 * and it keeps the marker maths trivial on the client.
 *
 * Run with: npm run build:map
 */
import { readFileSync, writeFileSync } from "node:fs";

const WIDTH = 1000;
const PAD = 8;
/** Points closer together than this (in viewBox units) are dropped. */
const MIN_STEP = 0.55;
/** Rings whose bounding box is smaller than this are dropped as noise. */
const MIN_RING = 1.6;

const gj = JSON.parse(readFileSync("scripts/data/gnb-adm1.geojson", "utf8"));

/** Regions we actively buy in, and how each should read on the map. */
const SOURCING = new Set(["Bafatá", "Gabu", "Oio", "Quinara", "Cacheu"]);
const LABELS = { Gabu: "Gabú" };

/* ------------------------------------------------------------- bounds */

const allCoords = [];
for (const f of gj.features) {
  const c = f.geometry.coordinates;
  allCoords.push(...(f.geometry.type === "Polygon" ? c.flat() : c.flat(2)));
}

const lngs = allCoords.map((p) => p[0]);
const lats = allCoords.map((p) => p[1]);
const minLng = Math.min(...lngs);
const maxLng = Math.max(...lngs);
const minLat = Math.min(...lats);
const maxLat = Math.max(...lats);

const midLat = (minLat + maxLat) / 2;
const kx = Math.cos((midLat * Math.PI) / 180);
const scale = (WIDTH - PAD * 2) / ((maxLng - minLng) * kx);
const HEIGHT = Math.round((maxLat - minLat) * scale + PAD * 2);

const project = (lng, lat) => [
  PAD + (lng - minLng) * kx * scale,
  // SVG y grows downward; latitude grows upward.
  PAD + (maxLat - lat) * scale,
];

/* -------------------------------------------------------------- paths */

const ringToPath = (ring) => {
  const pts = ring.map(([lng, lat]) => project(lng, lat));

  // Decimate: the source carries far more precision than 1000px can show.
  const kept = [pts[0]];
  for (let i = 1; i < pts.length; i++) {
    const last = kept[kept.length - 1];
    if (Math.hypot(pts[i][0] - last[0], pts[i][1] - last[1]) >= MIN_STEP) {
      kept.push(pts[i]);
    }
  }
  if (kept.length < 3) return null;

  const xs = kept.map((p) => p[0]);
  const ys = kept.map((p) => p[1]);
  if (
    Math.max(...xs) - Math.min(...xs) < MIN_RING &&
    Math.max(...ys) - Math.min(...ys) < MIN_RING
  ) {
    return null;
  }

  const f = (n) => n.toFixed(1);
  return (
    `M${f(kept[0][0])} ${f(kept[0][1])}` +
    kept
      .slice(1)
      .map((p) => `L${f(p[0])} ${f(p[1])}`)
      .join("") +
    "Z"
  );
};

/** Area-weighted centroid, so labels land inside the biggest landmass. */
const centroidOf = (rings) => {
  let best = null;
  let bestArea = -1;
  for (const ring of rings) {
    let a = 0;
    let cx = 0;
    let cy = 0;
    for (let i = 0; i < ring.length; i++) {
      const [x1, y1] = ring[i];
      const [x2, y2] = ring[(i + 1) % ring.length];
      const cross = x1 * y2 - x2 * y1;
      a += cross;
      cx += (x1 + x2) * cross;
      cy += (y1 + y2) * cross;
    }
    a *= 0.5;
    if (Math.abs(a) > bestArea) {
      bestArea = Math.abs(a);
      best = [cx / (6 * a), cy / (6 * a)];
    }
  }
  return best;
};

const regions = gj.features
  .map((f) => {
    const name = f.properties.shapeName;
    const rings =
      f.geometry.type === "Polygon"
        ? f.geometry.coordinates
        : f.geometry.coordinates.flat();

    const d = rings.map(ringToPath).filter(Boolean).join("");
    const [cx, cy] = centroidOf(rings.map((r) => r.map(([lng, lat]) => project(lng, lat))));

    return {
      id: f.properties.shapeISO,
      name: LABELS[name] ?? name,
      sourcing: SOURCING.has(name),
      d,
      cx: Number(cx.toFixed(1)),
      cy: Number(cy.toFixed(1)),
    };
  })
  // Draw the sourcing regions last so their highlight sits on top.
  .sort((a, b) => Number(a.sourcing) - Number(b.sourcing));

/* -------------------------------------------------------------- pins */

const PINS = [
  { id: "bissau", name: "Bissau", role: "Capital · export port", lat: 11.8637, lng: -15.5977 },
].map((p) => {
  const [x, y] = project(p.lng, p.lat);
  return { ...p, x: Number(x.toFixed(1)), y: Number(y.toFixed(1)) };
});

/* ------------------------------------------------------------ output */

const ts = `// AUTO-GENERATED by scripts/build-country.mjs — do not edit by hand.
//
// Source: geoBoundaries gbOpen ADM1, built from OpenStreetMap data.
// Licence: Open Data Commons Open Database License (ODbL) v1.0.
// Attribution is rendered alongside the map, as the licence requires.

export type Region = {
  id: string;
  name: string;
  /** True for the regions we actively buy raw cashew in. */
  sourcing: boolean;
  d: string;
  cx: number;
  cy: number;
};

export type Pin = {
  id: string;
  name: string;
  role: string;
  lat: number;
  lng: number;
  x: number;
  y: number;
};

export const GNB_VIEWBOX = { w: ${WIDTH}, h: ${HEIGHT} } as const;

export const gnbRegions: Region[] = ${JSON.stringify(regions, null, 2)};

export const gnbPins: Pin[] = ${JSON.stringify(PINS, null, 2)};
`;

writeFileSync("src/data/guinea-bissau.ts", ts);

console.log(
  `guinea-bissau.ts · viewBox ${WIDTH}x${HEIGHT} · ${regions.length} regions · ` +
    `${Math.round(ts.length / 1024)}kb · sourcing: ${regions.filter((r) => r.sourcing).map((r) => r.name).join(", ")}`,
);
